/*
    JSX (Syntactic Sugar)는
    React.createElement의 신택틱 슈거다!
    => React.CreateElement("h1", {class: "titile"}, "Hello, React!");
    너무 복잡함..


    JSX의 규칙
    - 반드시 하나의 루트 태그만 반환해야한다. <div>
        ㄴ 근데 div 같은 루트태그 없이 그냥 h1, h2만 쓰고싶으면?
            ㄴ <React.Fragment></React.Fragment> 로 감싸면, 그룸으로 감싸지 않음
                ㄴ 근데 너무 길어서 단축문법인 <></>가 생겼음 이거 쓰면 됨

    - 여러 줄을 리턴할 때는 소괄호로 작성 (권장사항, 필수는 아님)

    - 반드시 태그는 닫아준다. 
        ㄴHTML5에서 빈 태그는 마지막에 <br>을 넣음 (</br>처럼 닫지 않음)
            ㄴ 하지만, JSX에서는 반드시 태그는 닫아준다는 특징이 있음
                ㄴ <br />로 닫아줘야 함

    - 태그의 속성은 카멜 케이스로 한다
        ㄴ class -> className

    - JSX는 표현식을 사용할 수 있다
        ㄴ 간단한 표현식은 중괄호로 사용 {}

    - 인라인 스타일은 객체로 사용할 수 있다

    - 함수형 컴포넌트의 이름은 항상 대문자로 시작해야한다
        ㄴ App (GOOD) app (BAD)
*/
