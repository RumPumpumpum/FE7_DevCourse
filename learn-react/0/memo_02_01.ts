/*
    - 컴포넌트(Component)
        UI를 구성하는 가장 작은 단위이자, 재사용 가능한 독립적인 블록을 의미
    
    - 컴포넌트의 정의 방법
        ㄴ 클래스형 컴포넌트 (Class Component)
            ㄴ React.Component를 상속받아 만들며, render() 메서드 안에 JSX를 반환     
        ㄴ 함수형 컴포넌트 (Function Component)
            ㄴ  함수로 정의하며, props를 받아 JSX를 반환 

    - 컴포넌트의 공통적인 특징
        JSX 문법을 리턴한다는 것
        JSX문법은 Javascript + XML 확장 문법으로, 자바스크립트 안에서 HTML과 비슷한 구문을
        쓸 수 있게 해주는 확장 문법

    1. 클래스형 컴포넌트는 리액트 초창기부터 존재했던 방식
    2. 함수형 컴포넌트는 리액트 0.14버전 (2015)
    3. React 16.8 (2019년 2월) 리액트 훅(react hooks)지원
        ㄴ 이것을 기점으로 함수형 컴포넌트 사용 시작
        ㄴ 클래스형 컴포넌트는 클래스 생성/종료 시점을 코드로 체크를 가능할 수 있었음
            ㄴ 함수형 컴포넌트는 안됐음, 리액트 훅 기점으로 생명주기 확인 가능
        ㄴ 둘 다 생성주기 확인 가능하니, 더 쉬운 함수형 컴포넌트가 뜨기 시작
    4. React 19 부터 클래스형 컴포넌트를 배제하기 시작함
    
*/

